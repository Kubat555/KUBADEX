function toPath(rows) {
  let d = ''
  rows.forEach((row, y) => {
    for (const run of row.matchAll(/#+/g)) d += `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`
  })
  return d
}

/** Icon name -> SVG path data in a 16×16 viewBox. */
export const ICONS = Object.fromEntries(Object.entries(GRIDS).map(([name, rows]) => [name, toPath(rows)]))
